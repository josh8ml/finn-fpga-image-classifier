"""Collect every result JSON under runs/ into Markdown tables (results/summary.md).

    python scripts/collect_results.py

Numbers are copied from the files the other scripts wrote; nothing is typed in by
hand. Each table states its result type. The small JSON/report files are also
copied to results/<model>/ so they can be committed (runs/ itself is git-ignored
because it holds large build outputs).
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS = REPO / "runs"
MODELS = ["fp32", "w4a4", "w2a2"]


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def pct(x):
    return f"{x * 100:.2f}%" if x is not None else "n/a"


def estimate_summary(report_dir: Path):
    perf = load(report_dir / "estimate_network_performance.json")
    res = load(report_dir / "estimate_layer_resources.json")
    if not perf or not res:
        return None
    layers = {k: v for k, v in res.items() if k != "total"}
    return {
        "fps": perf["estimated_throughput_fps"],
        "lat_us": perf["estimated_latency_ns"] / 1000,
        "bottleneck": perf["max_cycles_node_name"],
        "LUT": sum(v.get("LUT", 0) for v in layers.values()),
        "BRAM_18K": sum(v.get("BRAM_18K", 0) for v in layers.values()),
        "DSP": sum(v.get("DSP", 0) for v in layers.values()),
    }


KEEP = [
    "metrics.json", "export_check.json", "finn_accuracy.json", "cpu_baseline.json", "folding_sweep.json",
    "finn_estimate/report/*.json", "finn_estimate/auto_folding_config.json",
    "finn_full/report/*", "finn_full/final_hw_config.json", "finn_full/time_per_step.json",
]


def copy_small_results() -> None:
    for m in MODELS:
        src = RUNS / m
        if not src.exists():
            continue
        for pattern in KEEP:
            for f in src.glob(pattern):
                if f.is_file() and f.stat().st_size < 5_000_000:
                    dest = REPO / "results" / m / f.relative_to(src)
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(f, dest)


def main() -> None:
    copy_small_results()
    out = ["# Results summary (generated by scripts/collect_results.py)", ""]

    out += ["## Accuracy on the Fashion-MNIST test set", "", "Result type: measured (software).", "",
            "| Model | Test accuracy (10k images) | Parameters | Epochs | Train time | Export matches Brevitas | FINN streamlined accuracy |",
            "|---|---:|---:|---:|---:|---|---|"]
    for m in MODELS:
        met = load(RUNS / m / "metrics.json")
        if not met:
            continue
        exp = load(RUNS / m / "export_check.json")
        fa = load(RUNS / m / "finn_accuracy.json")
        exp_s = (f"yes ({exp['images']} imgs, max diff {exp['max_abs_logit_diff']:.1e})" if exp and exp["allclose_atol_1e-4"]
                 else ("NO" if exp else "n/a"))
        fa_s = (f"{pct(fa['finn_accuracy'])} on {fa['images']} imgs, {pct(fa['top1_agreement_finn_vs_brevitas'])} agree with Brevitas"
                if fa else "n/a")
        out.append(f"| {m} | {pct(met['test_accuracy'])} | {met['parameters']:,} | {met['epochs']} | {met['train_time_s']:.0f} s | {exp_s} | {fa_s} |")

    cpu = load(RUNS / "fp32" / "cpu_baseline.json")
    if cpu:
        bkey = next(k for k in cpu if k.startswith("batch") and k.endswith("throughput_img_per_s") and not k.startswith("batch1_"))
        out += ["", "## CPU baseline (FP32 PyTorch)", "", "Result type: measured (software).", "",
                "| CPU | Threads | Batch-1 latency (median) | Batch-1 throughput | Batched throughput | Accuracy |",
                "|---|---:|---:|---:|---:|---:|",
                f"| {cpu['cpu']} | {cpu['torch_threads']} | {cpu['batch1_latency_us_median']} µs | "
                f"{cpu['batch1_throughput_img_per_s']:,.0f} img/s | {cpu[bkey]:,.0f} img/s ({bkey.split('_')[0]}) | {pct(cpu['test_accuracy'])} |"]

    out += ["", "## FINN estimates at the default target (10,000 img/s requested, 100 MHz, AUP-ZU3)", "",
            "Result type: estimate (FINN analytical model). Not measured.", "",
            "| Model | Est. throughput | Est. latency | Est. LUTs | Est. BRAM18 | Est. DSPs | Bottleneck layer |",
            "|---|---:|---:|---:|---:|---:|---|"]
    for m in MODELS[1:]:
        e = estimate_summary(RUNS / m / "finn_estimate" / "report")
        if e:
            out.append(f"| {m} | {e['fps']:,.0f} img/s | {e['lat_us']:,.1f} µs | {e['LUT']:,.0f} | {e['BRAM_18K']} | {e['DSP']} | {e['bottleneck']} |")

    for m in MODELS[1:]:
        sw = load(RUNS / m / "folding_sweep.json")
        if not sw:
            continue
        out += ["", f"## Throughput vs. area sweep ({m})", "", f"Result type: {sw['result_type']}.", "",
                "| Target img/s | Est. img/s | Est. LUTs | Est. BRAM18 | Est. DSPs | Bottleneck |",
                "|---:|---:|---:|---:|---:|---|"]
        for r in sw["rows"]:
            out.append(f"| {r['target_fps']:,} | {r['estimated_throughput_fps']:,.0f} | {r['LUT']:,} | {r['BRAM_18K']} | {r['DSP']} | {r['bottleneck_layer']} |")

    for m in MODELS[1:]:
        rt = load(RUNS / m / "finn_full" / "report" / "rtlsim_performance.json")
        if rt:
            out += ["", f"## Stitched-IP RTL simulation ({m})", "", "Result type: simulation.", "", "```json",
                    json.dumps(rt, indent=2), "```"]

    dest = REPO / "results" / "summary.md"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\nWritten to {dest}")


if __name__ == "__main__":
    main()
